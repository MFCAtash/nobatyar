#!/bin/sh
# یک‌بار، روی ماشین توسعه (نیازمند اینترنت برای pnpm install):
#   ۱) pnpm install ⇒ pnpm-lock.yaml
#   ۲) مهاجرت init از schema.prisma (prisma migrate diff؛ بدون نیاز به دیتابیس)
#   ۳) هر SQL امنیتی prisma/sql/ORDER به‌عنوان مهاجرت بعدی، با «برچسب‌های زمانی واقعی و صعودی»
#   ۴) migration_lock.toml
# سپس (اختیاری ولی توصیه‌شده) روی یک Postgres خالی اعمال و بررسی می‌شود و در پایان check-repo-integrity اجرا می‌شود.
# خروجی را commit کنید: pnpm-lock.yaml و apps/api/prisma/migrations/
set -eu
ROOT="$(cd "$(dirname "$0")/.." && pwd)"
API="$ROOT/apps/api"
MIG="$API/prisma/migrations"

command -v pnpm >/dev/null 2>&1 || { echo "pnpm لازم است (corepack enable)"; exit 1; }
if [ -d "$MIG" ] && [ -n "$(ls -A "$MIG" 2>/dev/null)" ]; then
  echo "prisma/migrations از قبل پر است — این اسکریپت فقط برای «خط پایه‌ی اولیه» است." >&2
  echo "برای تغییر جدید: مهاجرت جدید بسازید (pnpm --filter @nobatyar/api db:phaseNN) و نام را به prisma/sql/ORDER اضافه کنید." >&2
  exit 1
fi

echo "→ pnpm install (ساخت pnpm-lock.yaml)"
(cd "$ROOT" && pnpm install)

echo "→ مهاجرت init از schema.prisma"
cd "$API"
stamp() { node -e 'const d=new Date(Date.now()+Number(process.argv[1])*1000);process.stdout.write(d.toISOString().replace(/[-:T]/g,"").slice(0,14))' "$1"; }
i=0
d="$MIG/$(stamp $i)_init"
mkdir -p "$d"
pnpm exec prisma migrate diff --from-empty --to-schema-datamodel prisma/schema.prisma --script > "$d/migration.sql"
[ -s "$d/migration.sql" ] || { echo "migration init خالی است" >&2; exit 1; }

while read -r f; do
  case "$f" in ''|'#'*) continue ;; esac
  i=$((i + 1))
  d="$MIG/$(stamp $i)_${f}"
  mkdir -p "$d"
  cp "prisma/sql/$f.sql" "$d/migration.sql"
  echo "  + $(basename "$d")"
done < prisma/sql/ORDER
printf '%s\n' '# Please do not edit this file manually' 'provider = "postgresql"' > "$MIG/migration_lock.toml"

echo "→ بررسی یکپارچگی"
sh "$ROOT/scripts/check-repo-integrity.sh"

cat <<'MSG'

✓ خط پایه ساخته شد. گام‌های بعد:
  1) (توصیه‌شده) اعمال روی Postgres خالی:  pnpm infra:up && sh scripts/ci-db-setup.sh   (بدون ALLOW_TEMP_MIGRATIONS)
     سپس: pnpm --filter @nobatyar/api test:int
  2) commit:  git add pnpm-lock.yaml apps/api/prisma/migrations && git commit -m "chore: lockfile + baseline migrations"
  3) خط «apps/api/prisma/migrations/» در .gitignore کامنت است؛ همان‌طور بماند.
MSG
