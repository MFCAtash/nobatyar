#!/bin/sh
# آماده‌سازی دیتابیس «تازه» برای CI و اجرای محلی تست‌های integration.
#   ۱) افزونه‌ها (infra/postgres/init.sql) ۲) نقش اپلیکیشن بدون BYPASSRLS (infra/postgres/01-roles.sh)
#   ۳) مهاجرت‌ها: فقط همان‌هایی که commit شده‌اند. بدون آن‌ها «شکست می‌خورد»، مگر ALLOW_TEMP_MIGRATIONS=true (گذرا؛ از schema.prisma + prisma/sql/ORDER).
# متغیرهای لازم: DATABASE_URL (مالک)، POSTGRES_USER/PASSWORD/DB، APP_DB_USER/PASSWORD
# اختیاری: PGHOST (پیش‌فرض 127.0.0.1)، PGPORT (پیش‌فرض 5432)
set -eu

ROOT="$(cd "$(dirname "$0")/.." && pwd)"
API="$ROOT/apps/api"

for v in DATABASE_URL POSTGRES_USER POSTGRES_PASSWORD POSTGRES_DB APP_DB_USER APP_DB_PASSWORD; do
  eval "val=\${$v:-}"
  [ -n "$val" ] || { echo "::error::$v is required"; exit 1; }
done
command -v psql >/dev/null 2>&1 || { echo "::error::psql (postgresql-client) is required"; exit 1; }

export PGHOST="${PGHOST:-127.0.0.1}" PGPORT="${PGPORT:-5432}" PGPASSWORD="$POSTGRES_PASSWORD"

echo "→ waiting for postgres"
i=0
until pg_isready -q -U "$POSTGRES_USER" -d "$POSTGRES_DB"; do
  i=$((i + 1))
  [ "$i" -lt 60 ] || { echo "::error::postgres is not ready"; exit 1; }
  sleep 1
done

echo "→ extensions"
psql -v ON_ERROR_STOP=1 -q -U "$POSTGRES_USER" -d "$POSTGRES_DB" -f "$ROOT/infra/postgres/init.sql"

echo "→ application role (NOSUPERUSER NOBYPASSRLS)"
sh "$ROOT/infra/postgres/01-roles.sh"

cd "$API"
MIG=prisma/migrations
if [ -d "$MIG" ] && [ -n "$(ls -A "$MIG" 2>/dev/null)" ]; then
  echo "→ using committed migrations"
elif [ "${ALLOW_TEMP_MIGRATIONS:-}" = "true" ]; then
  # گذرا (فقط CI/محلی، هرگز production): همان ترتیب prisma/sql/ORDER ولی با برچسب زمانی «واضحاً ساختگی» تا با مهاجرت واقعی اشتباه نشود.
  # راه‌حل ماندگار: sh scripts/bootstrap-baseline.sh  و commit ی lockfile + migrations. job ی Repo integrity تا آن موقع قرمز می‌ماند.
  echo "::warning::no committed migrations — building TEMPORARY migrations (ALLOW_TEMP_MIGRATIONS=true). Run scripts/bootstrap-baseline.sh and commit."
  mkdir -p "$MIG/20000101000001_init"
  pnpm exec prisma migrate diff --from-empty --to-schema-datamodel prisma/schema.prisma --script \
    > "$MIG/20000101000001_init/migration.sql"
  n=2
  while read -r f; do
    case "$f" in ''|'#'*) continue ;; esac
    d="$MIG/$(printf '200001010000%02d' "$n")_${f}"
    mkdir -p "$d"
    cp "prisma/sql/$f.sql" "$d/migration.sql"
    n=$((n + 1))
  done < prisma/sql/ORDER
  printf '%s\n' '# Please do not edit this file manually' 'provider = "postgresql"' > "$MIG/migration_lock.toml"
else
  echo "::error::apps/api/prisma/migrations خالی است. یک‌بار «sh scripts/bootstrap-baseline.sh» را اجرا و نتیجه را commit کنید (برای اجرای گذرای محلی/CI: ALLOW_TEMP_MIGRATIONS=true)." >&2
  exit 1
fi

echo "→ prisma migrate deploy"
pnpm exec prisma migrate deploy

echo "→ sanity checks"
psql -v ON_ERROR_STOP=1 -tA -U "$POSTGRES_USER" -d "$POSTGRES_DB" -c \
  "SELECT 'migrations applied: ' || count(*) FROM _prisma_migrations WHERE finished_at IS NOT NULL;"
BYPASS="$(psql -tA -U "$POSTGRES_USER" -d "$POSTGRES_DB" -c "SELECT rolbypassrls OR rolsuper FROM pg_roles WHERE rolname = '$APP_DB_USER'")"
[ "$BYPASS" = "f" ] || { echo "::error::app role must not be superuser/BYPASSRLS (got '$BYPASS')"; exit 1; }
echo "OK"
